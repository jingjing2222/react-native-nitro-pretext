type CaseBuilderConfig = {
  category: ParityCaseCategory;
  count: number;
  description: string;
  prefix: string;
  styleForIndex?: (index: number) => PretextStyle;
  texts: readonly string[];
};

function createParityCases({
  category,
  count,
  description,
  prefix,
  styleForIndex = () => PARITY_BASE_STYLE,
  texts,
}: CaseBuilderConfig): ParityCase[] {
  if (texts.length !== count) {
    throw new Error(
      `Expected ${count} fixed ${category} parity texts, got ${texts.length}`,
    );
  }

  return texts.map((text, index) => {
    const width = WIDTHS[(index * 5 + prefix.length) % WIDTHS.length] ?? 220;

    return {
      caseId: `${prefix}-${String(index + 1).padStart(3, "0")}`,
      category,
      description: `${description} #${index + 1}`,
      rnTextProps: DEFAULT_RN_TEXT_PROPS,
      style: styleForIndex(index),
      text,
      width,
    };
  });
}

if (STYLE_CROSS_CASES.length !== PARITY_CASE_DISTRIBUTION["style-cross"]) {
  throw new Error(
    `Expected ${PARITY_CASE_DISTRIBUTION["style-cross"]} fixed style-cross parity cases, got ${STYLE_CROSS_CASES.length}`,
  );
}

